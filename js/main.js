const themeBtn = document.getElementById("themeBtn");
const themeIcon = document.getElementById("themeIcon");
const menuBtn = document.getElementById("menuBtn");
const nav = document.getElementById("nav");

function updateTheme() {
    body.classList.toggle("dark", darkMode);
    themeIcon.textContent = darkMode ? "○" : "◐";
    localStorage.setItem("darkMode", darkMode);
}

function updateLanguage() {
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";

    document.querySelectorAll("[data-i18n]").forEach(element => {
        const key = element.dataset.i18n;

        if (translations[language][key]) {
            element.innerHTML = translations[language][key];
        }
    });

    languageBtn.textContent = language === "ar" ? "EN" : "AR";

    renderQuiz();
}

themeBtn.addEventListener("click", () => {
    darkMode = !darkMode;
    updateTheme();
});

languageBtn.addEventListener("click", () => {
    language = language === "ar" ? "en" : "ar";
    localStorage.setItem("language", language);
    updateLanguage();
});

menuBtn.addEventListener("click", () => {
    nav.classList.toggle("active");
});

document.querySelectorAll(".nav a").forEach(link => {
    link.addEventListener("click", () => {
        nav.classList.remove("active");
    });
});

const weatherBtn = document.getElementById("weatherBtn");
const governorate = document.getElementById("governorate");
const weatherResult = document.getElementById("weatherResult");

async function getWeather() {
    const city = governorate.value;
    const location = locations[city];

    weatherResult.innerHTML = `
        <div class="weather-loading loading">
            <span></span>
            <p>${translations[language].loading}</p>
        </div>
    `;

    try {
        const url =
            `https://api.open-meteo.com/v1/forecast?latitude=${location.lat}&longitude=${location.lon}&current=temperature_2m,wind_speed_10m&timezone=Africa%2FCairo`;

        const response = await fetch(url);

        if (!response.ok) {
            throw new Error("API Error");
        }

        const data = await response.json();

        const temperature = data.current.temperature_2m;
        const wind = data.current.wind_speed_10m;
        const timezone = data.timezone;

        weatherResult.innerHTML = `
            <div class="weather-card">

                <div class="weather-main">

                    <div>
                        <div class="weather-location">
                            ${locationNames[language][city]}
                        </div>

                        <div class="temperature">
                            ${temperature}°C
                        </div>
                    </div>

                    <div class="api-badge">
                        <span></span>
                        LIVE API DATA
                    </div>

                </div>

                <div class="weather-stat">
                    <span>${translations[language].temperature}</span>
                    <strong>${temperature} °C</strong>
                </div>

                <div class="weather-stat">
                    <span>${translations[language].wind}</span>
                    <strong>${wind} km/h</strong>
                </div>

                <div class="weather-stat">
                    <span>${translations[language].timezone}</span>
                    <strong>${timezone}</strong>
                </div>

            </div>
        `;

    } catch (error) {
        weatherResult.innerHTML = `
            <div class="weather-loading">
                <p>${translations[language].error}</p>
            </div>
        `;
    }
}

weatherBtn.addEventListener("click", getWeather);

