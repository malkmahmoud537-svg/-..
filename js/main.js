function renderQuiz() {
    const quiz = quizData[language][currentQuestion];

    document.getElementById("question").textContent = quiz.question;

    document.getElementById("questionNumber").textContent =
        `0${currentQuestion + 1} / 04`;

    document.getElementById("progress").style.width =
        `${((currentQuestion + 1) / 4) * 100}%`;

    document.getElementById("score").textContent =
        `${translations[language].score}: ${score}`;

    const answers = document.getElementById("answers");

    answers.innerHTML = "";

    quiz.answers.forEach((answer, index) => {
        const button = document.createElement("button");

        button.className = "answer";
        button.textContent = answer;

        button.addEventListener("click", () => {
            chooseAnswer(index, button);
        });

        answers.appendChild(button);
    });

    answered = false;
}

function chooseAnswer(index, selectedButton) {
    if (answered) {
        return;
    }

    answered = true;

    const quiz = quizData[language][currentQuestion];
    const buttons = document.querySelectorAll(".answer");

    buttons.forEach((button, buttonIndex) => {
        if (buttonIndex === quiz.correct) {
            button.classList.add("correct");
        }
    });

    if (index === quiz.correct) {
        selectedButton.classList.add("correct");
        score++;
    } else {
        selectedButton.classList.add("wrong");
    }

    document.getElementById("score").textContent =
        `${translations[language].score}: ${score}`;
}

document.getElementById("nextBtn").addEventListener("click", () => {
    if (!answered) {
        return;
    }

    currentQuestion++;

    if (currentQuestion >= quizData[language].length) {
        currentQuestion = 0;
        score = 0;
    }

    renderQuiz();
});

